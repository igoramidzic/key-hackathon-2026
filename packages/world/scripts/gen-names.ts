// pnpm --filter @sim/world gen:names — regenerates src/names.generated.ts from seeded Faker.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { GENERATED_PEOPLE } from '../src/constants';
import { drawNames } from './names';

const names = drawNames(GENERATED_PEOPLE);
const out = fileURLToPath(new URL('../src/names.generated.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/gen-names.ts from Faker (en, seed WORLD_SEED). Do not edit.\nexport const NAMES: readonly (readonly [string, string])[] = ${JSON.stringify(names)};\n`,
);
console.log(`wrote ${names.length} names to ${out}`);
