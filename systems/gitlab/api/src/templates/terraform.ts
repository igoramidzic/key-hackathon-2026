import { type Knobs, lines, type RepoContext } from './context';

type Files = Record<string, string>;

export function renderTerraform(ctx: RepoContext, k: Knobs): Files {
  const app = ctx.app;
  const svc = app.runtime.service;
  const sa = `${svc}`.slice(0, 26);
  return {
    'versions.tf': lines(
      'terraform {',
      '  required_version = ">= 1.7.0"',
      '',
      '  required_providers {',
      '    google = {',
      '      source  = "hashicorp/google"',
      `      version = "~> ${k.deps.google}"`,
      '    }',
      '  }',
      '',
      '  backend "gcs" {',
      `    prefix = "${ctx.tlaLower}00/${ctx.repo.name}"`,
      '  }',
      '}',
      '',
      'provider "google" {',
      '  project = var.project_id',
      '  region  = var.region',
      '}',
      '',
    ),
    'main.tf': lines(
      'locals {',
      '  labels = {',
      `    app_tla     = "${ctx.tlaLower}"`,
      `    app_name    = "${app.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}"`,
      `    tier        = "tier-${app.tier}"`,
      '    managed_by  = "terraform"',
      '  }',
      '}',
      '',
      'resource "google_service_account" "workload" {',
      `  account_id   = "${sa}"`,
      `  display_name = "${app.name} workload identity"`,
      '}',
      '',
      'resource "google_service_account_iam_member" "workload_identity" {',
      '  service_account_id = google_service_account.workload.name',
      '  role               = "roles/iam.workloadIdentityUser"',
      `  member             = "serviceAccount:\${var.project_id}.svc.id.goog[${app.runtime.namespace}/${svc}]"`,
      '}',
      '',
      'resource "google_sql_database_instance" "primary" {',
      `  name             = "${ctx.tlaLower}00-pg-\${var.environment}"`,
      '  database_version = "POSTGRES_15"',
      '  region           = var.region',
      '',
      '  settings {',
      '    tier              = var.db_tier',
      '    availability_type = var.environment == "prod" ? "REGIONAL" : "ZONAL"',
      '    user_labels       = local.labels',
      '',
      '    backup_configuration {',
      '      enabled                        = true',
      '      point_in_time_recovery_enabled = true',
      '      backup_retention_settings {',
      '        retained_backups = var.backup_retention_days',
      '      }',
      '    }',
      '',
      '    ip_configuration {',
      '      ipv4_enabled    = false',
      '      private_network = var.vpc_self_link',
      '    }',
      '  }',
      '',
      '  deletion_protection = true',
      '}',
      '',
      'resource "google_pubsub_topic" "events" {',
      `  name   = "${ctx.tlaLower}-events"`,
      '  labels = local.labels',
      '}',
      '',
      'resource "google_secret_manager_secret" "db_password" {',
      `  secret_id = "${ctx.tlaLower}00-db-password"`,
      '  labels    = local.labels',
      '  replication {',
      '    auto {}',
      '  }',
      '}',
      '',
      'module "workload" {',
      '  source = "git::https://gitlab.com/keybank/platform/terraform-gke-workload.git?ref=v3.4.0"',
      '',
      `  name          = "${svc}"`,
      `  namespace     = "${app.runtime.namespace}"`,
      `  cluster       = "${app.runtime.cluster}"`,
      '  min_replicas  = var.min_replicas',
      '  max_replicas  = var.max_replicas',
      '  cpu           = var.cpu',
      '  memory        = var.memory',
      '  service_account_email = google_service_account.workload.email',
      '  labels        = local.labels',
      '}',
      '',
    ),
    'variables.tf': lines(
      'variable "project_id" {',
      '  type        = string',
      '  description = "GCP project id"',
      '}',
      '',
      'variable "environment" {',
      '  type        = string',
      '  description = "prod or nonprod"',
      '}',
      '',
      'variable "region" {',
      '  type    = string',
      `  default = "${app.runtime.region}"`,
      '}',
      '',
      'variable "vpc_self_link" {',
      '  type = string',
      '}',
      '',
      'variable "db_tier" {',
      '  type    = string',
      `  default = "${k.infra.dbTier}"`,
      '}',
      '',
      'variable "backup_retention_days" {',
      '  type    = number',
      `  default = ${k.infra.backupRetentionDays}`,
      '}',
      '',
      'variable "min_replicas" {',
      '  type    = number',
      `  default = ${k.infra.minReplicas}`,
      '}',
      '',
      'variable "max_replicas" {',
      '  type    = number',
      `  default = ${k.infra.maxReplicas}`,
      '}',
      '',
      'variable "cpu" {',
      '  type    = string',
      `  default = "${k.infra.cpu}"`,
      '}',
      '',
      'variable "memory" {',
      '  type    = string',
      `  default = "${k.infra.memory}"`,
      '}',
      '',
    ),
    'outputs.tf': lines(
      'output "service_account_email" {',
      '  value = google_service_account.workload.email',
      '}',
      '',
      'output "db_connection_name" {',
      '  value = google_sql_database_instance.primary.connection_name',
      '}',
      '',
      'output "events_topic" {',
      '  value = google_pubsub_topic.events.id',
      '}',
      '',
    ),
    'envs/prod.tfvars': lines(
      `project_id    = "${app.runtime.gcpProject}"`,
      'environment   = "prod"',
      `region        = "${app.runtime.region}"`,
      `vpc_self_link = "projects/kb-net-host/global/networks/kb-prod-vpc"`,
      `min_replicas  = ${k.infra.minReplicas}`,
      `max_replicas  = ${k.infra.maxReplicas}`,
      '',
    ),
    'envs/nonprod.tfvars': lines(
      `project_id    = "${app.runtime.gcpProject.replace('-prod-', '-np-')}"`,
      'environment   = "nonprod"',
      `region        = "${app.runtime.region}"`,
      'vpc_self_link = "projects/kb-net-host/global/networks/kb-nonprod-vpc"',
      'db_tier       = "db-custom-1-3840"',
      'min_replicas  = 1',
      'max_replicas  = 2',
      '',
    ),
  };
}
